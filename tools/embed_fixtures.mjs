#!/usr/bin/env node
// Embed fixtures/*.json (payload + golden) into test/test_dosipas/fixtures_data.c so
// the tests need no file system (they run on the ESP32 too).
//
//   node tools/embed_fixtures.mjs
//
// Also writes fuzz/corpus/<name>.bin seeds from the payloads.

import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '..');
const fixturesDir = join(repo, 'fixtures');
const outC = join(repo, 'test', 'test_dosipas', 'fixtures_data.c');
const outH = join(repo, 'test', 'test_dosipas', 'fixtures_data.h');
const corpusDir = join(repo, 'fuzz', 'corpus');

const files = readdirSync(fixturesDir).filter(f => f.endsWith('.json')).sort();
if (files.length === 0) throw new Error('no fixtures/*.json: run tools/gen_golden.mjs first');

function cBytes(buf) {
  const lines = [];
  for (let i = 0; i < buf.length; i += 24) {
    lines.push('  ' + [...buf.subarray(i, i + 24)].map(b => '0x' + b.toString(16).padStart(2, '0')).join(','));
  }
  return lines.join(',\n');
}

function cString(s) {
  // Chunks of adjacent literals keep every line short; the content is ASCII JSON
  // except for UTF-8 names, which are escaped as octal so the file stays ASCII.
  const bytes = Buffer.from(s, 'utf8');
  let out = '';
  let line = '  "';
  for (const b of bytes) {
    let piece;
    if (b === 0x22) piece = '\\"';
    else if (b === 0x5c) piece = '\\\\';
    else if (b === 0x0a) piece = '\\n';
    else if (b < 0x20 || b >= 0x7f) piece = '\\' + b.toString(8).padStart(3, '0');
    else piece = String.fromCharCode(b);
    line += piece;
    if (line.length > 100) {
      out += line + '"\n';
      line = '  "';
    }
  }
  return out + line + '"';
}

let version = 'unknown';
const entries = [];
const c = [];
c.push('/* Generated by tools/embed_fixtures.mjs from the fixtures directory. DO NOT EDIT. */');
c.push('#include "fixtures_data.h"');
c.push('');
mkdirSync(corpusDir, { recursive: true });
for (const f of files) {
  const g = JSON.parse(readFileSync(join(fixturesDir, f), 'utf8'));
  version = g.dosipasTsVersion;
  const payload = Buffer.from(g.hex, 'hex');
  const id = g.name.replace(/[^A-Za-z0-9]/g, '_');
  c.push(`static const uint8_t payload_${id}[${payload.length}] = {\n${cBytes(payload)}\n};`);
  // The golden JSON without the payload hex (saves flash; the payload is the byte array).
  const { hex, ...golden } = g;
  c.push(`static const char golden_${id}[] =\n${cString(JSON.stringify(golden))};`);
  c.push('');
  entries.push(`  {"${g.name}", payload_${id}, ${payload.length}, golden_${id}},`);
  writeFileSync(join(corpusDir, `${g.name}.bin`), payload);
}
c.push(`const fixture_t FIXTURES[${entries.length}] = {\n${entries.join('\n')}\n};`);
c.push(`const size_t FIXTURE_COUNT = ${entries.length};`);
c.push(`const char *const FIXTURES_DOSIPAS_TS_VERSION = "${version}";`);
c.push('');

const h = `/* Generated by tools/embed_fixtures.mjs. DO NOT EDIT. */
#ifndef FIXTURES_DATA_H
#define FIXTURES_DATA_H
#include <stddef.h>
#include <stdint.h>
#ifdef __cplusplus
extern "C" {
#endif
typedef struct {
    const char *name;
    const uint8_t *payload;
    size_t payload_len;
    const char *golden; /* JSON: ticket, time helpers, signed bytes, verification results */
} fixture_t;
extern const fixture_t FIXTURES[];
extern const size_t FIXTURE_COUNT;
extern const char *const FIXTURES_DOSIPAS_TS_VERSION;
#ifdef __cplusplus
}
#endif
#endif
`;
writeFileSync(outC, c.join('\n'));
writeFileSync(outH, h);
console.log(`embedded ${entries.length} fixtures (dosipas-ts ${version}) into ${outC}`);
